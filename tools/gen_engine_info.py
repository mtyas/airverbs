#!/usr/bin/env python3
"""Build source/airwindows/EngineInfo.inc from engine_params.json + Airwindopedia.txt.

Adds Airverbs-specific knowledge on top of the raw Airwindows metadata:
family, one-line description, macro role of each parameter (which of the Size / Decay /
Tone macros drives it), and a loudness trim so engines sit at comparable levels."""
import json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
engines = json.load(open(os.path.join(root, "tools/engine_params.json")))
pedia_path = os.path.join(root, "third_party/airwindows/Airwindopedia.txt")
if not os.path.exists(pedia_path):
    pedia_path = os.path.join(root, "Airwindopedia.txt")
pedia = open(pedia_path, encoding="utf-8").read()
trims_path = os.path.join(root, "tools/engine_trims.json")
trims = json.load(open(trims_path)) if os.path.exists(trims_path) else {}

FAMILIES = [
    ("Halls & Cathedrals", "kCathedral kCathedral2 kCathedral3 kCathedral4 kCathedral5 kBeyond kCosmos kRockstar kRockstar2 kGuitarHall kGuitarHall2 VerbSevens VerbSixes"),
    ("Rooms & Chambers",   "kStation kWoodRoom kCyberCity kAlienSpaceship Chamber Chamber2 kChamberAR Verbity Verbity2 Reverb PocketVerbs ClearCoat"),
    ("Plates",             "kPlateA kPlateB kPlateC kPlateD kPlate140 kPlate240 CreamCoat CrunchCoat"),
    ("Cosmic & Lush",      "Galactic Galactic2 Galactic3 Infinity Infinity2 MatrixVerb NonlinearSpace VerbTiny VerbThic Ultralight Ultralight2"),
    ("Lo-Fi & Strange",    "MV MV2 StarChild StarChild2 Melt CloudCoat"),
    ("Ambience",           "BrightAmbience BrightAmbience2 BrightAmbience3"),
]
family_of = {n: i for i, (_, names) in enumerate(FAMILIES) for n in names.split()}

ROLE = {  # parameter name -> role
    "Bigness": "Size", "Big": "Size", "Size": "Size", "RmSize": "Size", "Delay": "Size", "Length": "Size", "Depth": "Size",
    "Regen": "Decay", "Sustain": "Decay", "Longness": "Decay", "Feedback": "Decay", "Feedbck": "Decay", "RT60": "Decay",
    "Livenes": "Decay", "Replace": "DecayInv",
    "Filter": "Tone", "Bright": "Tone", "Brightne": "Tone", "Brightns": "Tone", "Treble": "Tone", "Liteness": "Tone", "Top dB": "Tone",
    "Darkness": "ToneInv", "Darken": "ToneInv", "Mulch": "ToneInv", "Damping": "ToneInv",
    "Dry/Wet": "Wet", "Wet": "Wet", "Wetness": "Wet",
}
OVERRIDE = {("Ultralight2", "Damping"): "Decay"}

def describe(name):
    m = re.search(r"^############ " + re.escape(name) + r" (.*)$", pedia, re.M)
    if not m: return name
    return name + " " + m.group(1).strip()

def cstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["// Generated by tools/gen_engine_info.py - do not edit by hand.",
       "// ENGINE(name, family, trimDb, description, numParams, { params... })"]
for e in engines:
    n = e["name"]
    assert n in family_of, n
    params = []
    for p in e["params"]:
        role = OVERRIDE.get((n, p["name"]), ROLE.get(p["name"], "Other"))
        labels = p["labels"] if 0 < len(p["labels"]) <= 32 else []
        lo = hi = None
        if len(p["labels"]) > 32:
            try: lo, hi = float(p["labels"][0].rstrip("K")), float(p["labels"][-1].rstrip("K"))
            except ValueError: pass
        lab = "{" + ",".join(cstr(l) for l in labels) + "}"
        rng = f"true, {lo}f, {hi}f" if lo is not None else "false, 0.0f, 1.0f"
        params.append(f"    AIRVERBS_PARAM({cstr(p['name'])}, {p['def']:.4f}f, ParamRole::{role}, {rng}, {lab})")
    out.append(f"AIRVERBS_ENGINE_INFO({n}, {family_of[n]}, {trims.get(n, 0.0):.2f}f, {cstr(describe(n))},")
    out.append(",\n".join(params) if params else "    AIRVERBS_NO_PARAMS")
    out.append(")")
open(os.path.join(root, "source/airwindows/EngineInfo.inc"), "w").write("\n".join(out) + "\n")
fam = ["// Generated by tools/gen_engine_info.py"] + [f"AIRVERBS_FAMILY({cstr(f)})" for f, _ in FAMILIES]
open(os.path.join(root, "source/airwindows/FamilyList.inc"), "w").write("\n".join(fam) + "\n")
print("ok", len(engines))

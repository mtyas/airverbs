#!/usr/bin/env python3
"""Generate one wrapper translation unit per Airwindows reverb, plus the registry.

Each original Airwindows plugin is compiled unmodified inside its own namespace so their
global constants (delay lengths, enums) never collide."""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "third_party/airwindows/plugins/LinuxVST/src")
out = os.path.join(root, "source/airwindows/engines")
SKIP = {"Kalman", "GalacticVibe"}  # not reverbs
names = sorted(d for d in os.listdir(src) if os.path.isdir(os.path.join(src, d)) and d not in SKIP)
os.makedirs(out, exist_ok=True)
for n in names:
    with open(os.path.join(out, f"aw_{n}.cpp"), "w") as f:
        f.write(f"""// Generated by tools/gen_engines.py - wraps the original Airwindows {n} (MIT, Chris Johnson)
#include "audioeffectx.h"
namespace aw_{n} {{
#include "{n}/{n}.cpp"
#include "{n}/{n}Proc.cpp"
}}
AudioEffectX* aw_create_{n}() {{ return new aw_{n}::{n} (nullptr); }}
""")
with open(os.path.join(out, "EngineList.inc"), "w") as f:
    f.write("// Generated by tools/gen_engines.py\n")
    for n in names:
        f.write(f"AIRVERBS_ENGINE({n})\n")
print(len(names), "engines")
